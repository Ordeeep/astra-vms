 const savedFeatured=page.getByRole('button',{name:'Carregar visualização Destaque',exact:true});
 await savedFeatured.waitFor();
 await page.getByRole('button',{name:'Layout 2×2',exact:true}).click();
 await savedFeatured.click();
 assert(await featured.getAttribute('aria-pressed')==='true','Saved view must restore the asymmetric layout');
