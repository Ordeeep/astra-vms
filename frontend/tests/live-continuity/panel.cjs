 const theme=actions.getByRole('button',{name:'Tema escuro',exact:true});
 assert(await actions.getAttribute('data-slot')==='button-group','Vídeo Wall and theme must use the shared ButtonGroup');
 await theme.click();
 assert(await theme.getAttribute('aria-pressed')==='true','Theme must still toggle inside its button group');
 await theme.click();
