 assert(await page.getByRole('button',{name:'Recuar listagem',exact:true}).isVisible(),'Side toggle must return after fullscreen');
 await page.getByRole('tab',{name:'Câmeras',exact:true}).click();
 await page.getByRole('button',{name:'Layout 2×2',exact:true}).click();
 const cameraAt=position=>grid.locator(`[data-live-position="${position}"] .live-camera-title > span`).first().textContent();
 await page.getByRole('button',{name:'Arrastar Câmera 1',exact:true}).click();
 assert((await Promise.all([0,1,2,3].map(cameraAt))).join(',')==='Câmera 1,Câmera 2,Câmera 3,Câmera 4','Left click must fill the current layout in list order');
